def test_get_structured_summary(test_setup):
    repo = test_setup["repo"]
    proj_id = test_setup["project_id"]

    assistant = ProjectAssistant(repo=repo)
    data = assistant.get_structured_summary(proj_id)

    assert data["project_id"] == proj_id
    assert data["name"] == "CoreGateway"
    assert data["total_files"] == 2
    assert "main.py" in data["entry_points"]
    assert data["health_score"] == 78
    assert data["grade"] == "C"
