def test_summarize_project_local_mode(test_setup):
    repo = test_setup["repo"]
    proj_id = test_setup["project_id"]

    assistant = ProjectAssistant(repo=repo)
    res = assistant.summarize_project(proj_id)

    assert res["action"] == "summarize"
    assert res["provider"] == "local"
    assert "Executive Project Summary: CoreGateway" in res["content"]
    assert "Purpose & Technology" in res["content"]
    assert "Architecture & Structure" in res["content"]
    assert "78/100 (Grade C)" in res["content"]
    assert "Hardcoded JWT Secret" in res["content"]
    assert len(res["sources"]) > 0


def test_summarize_project_mock_provider(test_setup):
    repo = test_setup["repo"]
    proj_id = test_setup["project_id"]

    mock_provider = MockAIProvider(custom_response="Grounded executive summary generated by Mock Provider.")
    assistant = ProjectAssistant(repo=repo, ai_provider=mock_provider)

    res = assistant.summarize_project(proj_id, provider_name="mock")
    assert res["provider"] == "mock"
    assert res["content"] == "Grounded executive summary generated by Mock Provider."
    assert len(mock_provider.call_history) == 1
    # Verify mock provider received the evidence
    assert "CoreGateway" in mock_provider.call_history[0]["context"]
    assert "Hardcoded JWT Secret" in mock_provider.call_history[0]["context"]


